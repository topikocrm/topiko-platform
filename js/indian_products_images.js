// Smart image resolver
function getIndianProductImage(productId, productName, category, subcategory) {
    // 1. Check exact product ID match
    if (INDIAN_PRODUCT_IMAGES[productId]) {
        return INDIAN_PRODUCT_IMAGES[productId];
    }
    
    // 2. Try to find similar product by name keywords
    const nameLower = (productName || '').toLowerCase();
    const productKeys = Object.keys(INDIAN_PRODUCT_IMAGES);
    
    for (const key of productKeys) {
        const keyParts = key.split('-');
        for (const part of keyParts) {
            if (nameLower.includes(part) && part.length > 3) {
                return INDIAN_PRODUCT_IMAGES[key];
            }
        }
    }
    
    // 3. Use category-specific fallback
    if (CATEGORY_FALLBACK_IMAGES[subcategory]) {
        return CATEGORY_FALLBACK_IMAGES[subcategory];
    }
    
    if (CATEGORY_FALLBACK_IMAGES[category]) {
        return CATEGORY_FALLBACK_IMAGES[category];
    }
    
    // 4. Try to match product type
    const typeMapping = {
        'saree': CATEGORY_FALLBACK_IMAGES['sarees'],
        'kurta': CATEGORY_FALLBACK_IMAGES['kurtas'],
        'lehenga': CATEGORY_FALLBACK_IMAGES['lehengas'],
        'dress': CATEGORY_FALLBACK_IMAGES['western-wear'],
        'shoe': CATEGORY_FALLBACK_IMAGES['footwear'],
        'watch': CATEGORY_FALLBACK_IMAGES['accessories'],
        'bag': CATEGORY_FALLBACK_IMAGES['accessories']
    };
    
    for (const [keyword, image] of Object.entries(typeMapping)) {
        if (nameLower.includes(keyword)) {
            return image;
        }
    }
    
    // 5. Return null to trigger next fallback
    return null;
}

