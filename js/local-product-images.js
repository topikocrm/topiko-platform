    // Function to normalize product name for matching
    function normalizeProductName(name) {
        if (!name) return '';
        return name.toString()
            .toLowerCase()
            .replace(/[^a-z0-9]/g, '-')  // Replace non-alphanumeric with dash
            .replace(/-+/g, '-')          // Replace multiple dashes with single
            .replace(/^-|-$/g, '');       // Remove leading/trailing dashes
    }
    
    // Function to check for alternative image formats
    function checkAlternativeFormats(imagePath) {
        if (!imagePath || imagePath.includes('placeholder')) return imagePath;
        
        // If the original path has WebP, return it
        if (imagePath.endsWith('.webp')) return imagePath;
        
        // Extract base path without extension
        const basePath = imagePath.replace(/\.(jpg|jpeg|png|webp)$/i, '');
        
        // Return the original path - WebP fallback is handled by the image service
        // The productImageService will automatically check for WebP alternatives
        return imagePath;
    }
    
    // Function to get local product image with smart matching
    function getLocalProductImage(productId, category, productName) {
        // First check if we have a direct mapping
        if (LOCAL_PRODUCT_IMAGES[productId]) {
            return checkAlternativeFormats(LOCAL_PRODUCT_IMAGES[productId]);
        }
        
        // Try variations of the product ID
        const variations = [
            productId,
            productId.replace(/-/g, '_'),
            productId.replace(/_/g, '-'),
            productId.toLowerCase(),
            productId.replace(/-\d+$/, ''), // Remove trailing numbers
        ];
        
        for (let variant of variations) {
            if (LOCAL_PRODUCT_IMAGES[variant]) {
                console.log(`✅ Found image via ID variant: ${variant} for ${productId}`);
                return checkAlternativeFormats(LOCAL_PRODUCT_IMAGES[variant]);
            }
        }
        
        // Try smart product name matching
        if (productName) {
            const normalizedName = normalizeProductName(productName);
            
            // Direct normalized name match
            if (LOCAL_PRODUCT_IMAGES[normalizedName]) {
                console.log(`✅ Found image via normalized name: ${normalizedName} for "${productName}"`);
                return LOCAL_PRODUCT_IMAGES[normalizedName];
            }
            
            // Try with underscores instead of dashes
            const underscoreName = normalizedName.replace(/-/g, '_');
            if (LOCAL_PRODUCT_IMAGES[underscoreName]) {
                console.log(`✅ Found image via underscore name: ${underscoreName} for "${productName}"`);
                return LOCAL_PRODUCT_IMAGES[underscoreName];
            }
            
            // Try partial matching - find keys that contain the normalized name
            const nameWords = normalizedName.split('-').filter(w => w.length > 2);
            for (let key in LOCAL_PRODUCT_IMAGES) {
                if (!LOCAL_PRODUCT_IMAGES[key]) continue; // Skip null entries
                
                const keyNormalized = key.toLowerCase();
                // Check if all significant words from product name are in the key
                if (nameWords.length > 0 && nameWords.every(word => keyNormalized.includes(word))) {
                    console.log(`✅ Found image via partial match: ${key} for "${productName}"`);
                    return LOCAL_PRODUCT_IMAGES[key];
                }
            }
            
            // Try to find by first word (often the main product type)
            if (nameWords.length > 0) {
                const firstWord = nameWords[0];
                for (let key in LOCAL_PRODUCT_IMAGES) {
                    if (!LOCAL_PRODUCT_IMAGES[key]) continue;
                    if (key.toLowerCase().startsWith(firstWord)) {
                        console.log(`✅ Found image via first word match: ${key} for "${productName}"`);
                        return LOCAL_PRODUCT_IMAGES[key];
                    }
                }
            }
        }
        
        // Log what we couldn't find
        console.warn(`⚠️ No image found for: ID="${productId}", Name="${productName}", Category="${category}"`);
        
        // Return category-specific placeholder
        return CATEGORY_PLACEHOLDERS[category] || CATEGORY_PLACEHOLDERS['general'];
    }
    
    // Function to check if image exists locally
    function hasLocalImage(productId) {
        return LOCAL_PRODUCT_IMAGES[productId] !== null && LOCAL_PRODUCT_IMAGES[productId] !== undefined;
    }
    
    // Function to get all available product IDs
    function getAllProductIds() {
        return Object.keys(LOCAL_PRODUCT_IMAGES).filter(id => LOCAL_PRODUCT_IMAGES[id] !== null);
    }
    
