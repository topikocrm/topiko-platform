// Function to get static image for a product
function getStaticProductImage(productName) {
    const nameLower = productName.toLowerCase();
    
    // First try exact match
    if (STATIC_PRODUCT_IMAGES[nameLower]) {
        const images = STATIC_PRODUCT_IMAGES[nameLower];
        const randomIndex = Math.floor(Math.random() * images.length);
        return images[randomIndex];
    }
    
    // Then try partial match with longest match first
    let bestMatch = null;
    let bestMatchLength = 0;
    
    for (const [key, images] of Object.entries(STATIC_PRODUCT_IMAGES)) {
        if (nameLower.includes(key) && key.length > bestMatchLength) {
            bestMatch = images;
            bestMatchLength = key.length;
        }
    }
    
    if (bestMatch) {
        const randomIndex = Math.floor(Math.random() * bestMatch.length);
        return bestMatch[randomIndex];
    }
    
    return null;
}

